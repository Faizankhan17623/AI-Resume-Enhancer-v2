const express = require('express')
const route = express.Router()
const { Auth, isUser, isRecruiter, isApprovedRecruiter } = require('../Middlewares/Auth')
const { validate } = require('../Middlewares/Validate')
const { applicationCopilotSchema } = require('../Validation/schemas')
const { smartMatchSchema, createRoadmapSchema, createFollowUpSchema, toggleFollowUpSchema, interviewFeedbackSchema } = require('../Validation/Career')
const c = require('../controllers/Career')
route.get('/career/overview', Auth, isUser, c.getOverview)
route.post('/career/application-copilot', Auth, isUser, validate({ body: applicationCopilotSchema }), c.applicationCopilot)
route.post('/career/match', Auth, isUser, validate({ body: smartMatchSchema }), c.smartMatch)
route.post('/career/roadmap', Auth, isUser, validate({ body: createRoadmapSchema }), c.createRoadmap)
route.get('/career/follow-ups', Auth, isUser, c.listFollowUps)
route.post('/career/follow-ups', Auth, isUser, validate({ body: createFollowUpSchema }), c.createFollowUp)
route.patch('/career/follow-ups/:followUpId', Auth, isUser, validate({ body: toggleFollowUpSchema }), c.toggleFollowUp)
route.get('/career/profile', Auth, isUser, c.getProfile)
route.post('/career/profile/share', Auth, isUser, c.shareProfile)
route.get('/public/career/:shareId', c.getSharedProfile)
route.get('/public/jobs/:jobId/trust', c.jobTrust)
route.post('/career/interview-feedback', Auth, isUser, validate({ body: interviewFeedbackSchema }), c.interviewFeedback)
route.get('/jobs/:jobId/candidate-matches', Auth, isRecruiter, isApprovedRecruiter, c.recruiterMatches)
module.exports = route
